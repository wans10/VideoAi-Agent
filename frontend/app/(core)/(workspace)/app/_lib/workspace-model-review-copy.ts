export function workspaceModelReviewCopy(locale: string): Copy {
  return locale.startsWith('zh') ? zh : locale.startsWith('fr') ? fr : locale.startsWith('es') ? es : en;
}
export function workspaceModelSettingLabel(field: string, copy: Copy): string {
  return (
    copy.fields[field as keyof Copy['fields']] ??
    field.replace(/^extraInputValues\./, '').replaceAll('_', ' ')
  );
}
export function workspaceModelSettingValue(value: unknown, copy: Copy): string {
  if (value === undefined || value === null) return '—';
  if (typeof value === 'boolean') return value ? copy.on : copy.off;
  if (Array.isArray(value)) return `${value.length} ${copy.items}`;
  if (typeof value === 'object') return `${Object.keys(value).length} ${copy.items}`;
  const result = String(value);
  return result.length > 60 ? `${result.length} ${copy.characters}` : result;
}
